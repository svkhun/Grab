let language = 'en';
let staticNodes;
const englishToThai = new Map(Object.entries(staticThaiToEnglish).map(([th, en]) => [en, th]));
const translatableAttributes = ['aria-label', 'placeholder'];

export function getLanguage() { return language; }

export function t(key, params = {}) {
  const template = messages[key]?.[language] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? ''));
}

function rememberStaticContent() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (!node.parentElement || node.parentElement.closest('script, style')) continue;
    const original = node.textContent;
    if (englishToThai.has(original.trim())) nodes.push({ node, original, thai: englishToThai.get(original.trim()) });
  }
  const attributes = [];
  for (const element of document.querySelectorAll('[aria-label], [placeholder]')) {
    for (const name of translatableAttributes) {
      const original = element.getAttribute(name);
      if (englishToThai.has(original)) attributes.push({ element, name, original, thai: englishToThai.get(original) });
    }
  }
  staticNodes = { nodes, attributes };
}

export function setLanguage(next) {
  language = next === 'th' ? 'th' : 'en';
  if (!staticNodes) rememberStaticContent();
  for (const { node, original, thai } of staticNodes.nodes) {
    const padding = original.match(/^(\s*)(.*?)(\s*)$/s);
    node.textContent = language === 'th' ? `${padding[1]}${thai}${padding[3]}` : original;
  }
  for (const { element, name, original, thai } of staticNodes.attributes) {
    element.setAttribute(name, language === 'th' ? thai : original);
  }
  document.documentElement.lang = language;
  for (const button of document.querySelectorAll('[data-lang]')) {
    button.setAttribute('aria-pressed', String(button.dataset.lang === language));
  }
  try { localStorage.setItem('margin-missions-language', language); } catch { /* Private browsing may block storage. */ }
}

export function initialLanguage() {
  try { return localStorage.getItem('margin-missions-language') === 'th' ? 'th' : 'en'; }
  catch { return 'en'; }
}
